def generate_health_tips(symptom_set: set[str]) -> list[str]:
    """根据症状集合生成养生建议

    Args:
        symptom_set: 症状名称集合

    Returns:
        匹配的养生建议列表（含通用建议）
    """
    tips: list[str] = []
    for keywords, tip in _HEALTH_TIPS:
        if symptom_set & keywords:
            tips.append(f"• {tip}")
    tips.append("• 情志调畅：保持心情舒畅，避免过度思虑")
    tips.append("• 起居有常：规律作息，适当运动，避免熬夜")
    return tips
