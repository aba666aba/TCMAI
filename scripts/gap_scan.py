# 剔除占位项
all_ref = []
for cat, lst in ref_patent.items():
    for x in lst:
        if "占位" in x: continue
        all_ref.append((cat, x))

from collections import defaultdict
missing_by_cat = defaultdict(list)
recorded = []
for cat, name in all_ref:
    if name in patent_have:
        recorded.append(name)
    else:
        missing_by_cat[cat].append(name)

print("=== 中成药缺口扫描（参考清单 vs patent_medicines）===")
print("参考清单去重项: %d | 已收录: %d | 未收录(缺口): %d" % (len(all_ref), len(recorded), sum(len(v) for v in missing_by_cat.values())))
